"""Compress swisstopo's swissALTI3D link export into swissalti3d_years.txt.

Get the export from https://www.swisstopo.admin.ch/en/height-model-swissalti3d
(selection: whole Switzerland, resolution 2 m, format GeoTIFF, "export all links"),
then run:

    python make_swissalti3d_years.py <export.csv> > swissalti3d_years.txt

The only information per tile is its acquisition year; tile_manager.rs rebuilds the
URL from it. Tiles along a northing row with the same year are run-length encoded.
"""

import re
import sys

PATTERN = re.compile(r"swissalti3d_(\d{4})_(\d+)-(\d+)_2_2056_5728\.tif$")


def main(path: str) -> None:
    years: dict[tuple[int, int], int] = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            m = PATTERN.search(line)
            if m is None:
                sys.exit(f"unrecognised link: {line}")
            year, e, n = map(int, m.groups())
            years[(n, e)] = max(year, years.get((n, e), 0))

    runs: list[list[int]] = []
    for n, e in sorted(years):
        y = years[(n, e)]
        last = runs[-1] if runs else None
        if last and last[0] == n and last[1] + last[3] == e and last[2] == y:
            last[3] += 1
        else:
            runs.append([n, e, y, 1])

    out = sys.stdout
    out.reconfigure(newline="\n")
    out.write("# swissALTI3D (2 m, LV95) acquisition year per 1 km tile, generated by\n")
    out.write("# make_swissalti3d_years.py from swisstopo's link export.\n")
    out.write("# northing_km easting_km year count: tiles easting..easting+count-1 at that northing\n")
    for n, e, y, c in runs:
        out.write(f"{n} {e} {y} {c}\n")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
